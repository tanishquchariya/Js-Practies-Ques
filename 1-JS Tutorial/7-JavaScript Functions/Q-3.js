// // Question: Greeting Function

// // Write a JavaScript program that creates a function called:

// The function should:
// Take the user's name as a parameter.

// Return:
// Hello, Rahul!
// when the name is "Rahul".

// Call the function for 3 different names.
// Print each returned message using console.log().
// Input

// Use these values:
// Rahul
// Priya
// Amit
// Expected Output
// Hello, Rahul!
// Hello, Priya!
// Hello, Amit!

// Rules 🎯

// Use:
// function
// parameter
// argument
// return
// function call
// console.log()

// Don't use arrays or loops.


function myName(name) {
    return `Hello, ${name}`;
}
console.log(myName("Rahul"))
console.log(myName("Priya"))
console.log(myName("Amit"))
